// Course chapter type definition
export interface CourseChapter {
  id: number
  title: string
  titleEn: string
  num: string
  color: string
  bg: string
  topics: string[]
  subsections: string[]
  subsectionExercises: Record<string, number>  // 每个小节的习题数 { "小节名": 习题数 }
  progress: number
  status: 'new' | 'learning' | 'completed'
  lessons: number
}

// 计算章节总习题数
export function getChapterTotalExercises(chapter: CourseChapter): number {
  return Object.values(chapter.subsectionExercises).reduce((sum, count) => sum + count, 0)
}

