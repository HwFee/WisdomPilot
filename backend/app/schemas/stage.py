"""Stage API Schemas - 关卡相关数据传输对象"""

from datetime import datetime
from typing import Optional, List
from pydantic import BaseModel, Field


class StageBase(BaseModel):
    """Base stage schema"""
    title: str = Field(..., max_length=200)
    description: Optional[str] = None
    order_index: int = Field(..., ge=1)
    learning_objectives: List[str] = Field(default_factory=list)
    required_exercises: int = Field(default=5, ge=1)
    required_accuracy: float = Field(default=0.7, ge=0.0, le=1.0)
    verification_questions: int = Field(default=3, ge=1)
    xp_reward: int = Field(default=100, ge=0)
    quota_bonus: int = Field(default=3, ge=0)
    difficulty_level: int = Field(default=1, ge=1, le=5)


class StageSummary(StageBase):
    """Stage summary for listing"""
    id: int
    course_id: int
    chapter_id: Optional[int] = None
    is_active: bool = True

    model_config = {"from_attributes": True}


class StageDetail(StageSummary):
    """Stage detail with full info"""
    created_at: datetime
    updated_at: datetime

    model_config = {"from_attributes": True}


class UserStageProgressBase(BaseModel):
    """Base user stage progress schema"""
    stage_id: int
    status: str = "locked"  # locked, unlocked, in_progress, completed
    exercises_completed: int = 0
    exercises_correct: int = 0
    accuracy: float = 0.0
    verification_started: bool = False
    verification_passed: bool = False


class UserStageProgressResponse(UserStageProgressBase):
    """Response for user stage progress"""
    id: str
    user_id: str
    attempts: int = 0
    started_at: Optional[datetime] = None
    completed_at: Optional[datetime] = None

    model_config = {"from_attributes": True}

    @property
    def can_start_verification(self) -> bool:
        """Check if verification can be started"""
        return self.status == "in_progress" and self.accuracy >= 0.7 and self.exercises_completed >= 3

    @property
    def can_advance(self) -> bool:
        """Check if can advance to next stage"""
        return self.status == "completed"


class StageWithProgress(StageSummary):
    """Stage with user progress info"""
    progress: Optional[UserStageProgressResponse] = None


class StartStageRequest(BaseModel):
    """Request to start a stage"""
    pass


class StartStageResponse(BaseModel):
    """Response after starting a stage"""
    progress: UserStageProgressResponse
    message: str = "Stage started successfully"


class CompletedExercise(BaseModel):
    """Single completed exercise info"""
    exercise_id: int
    exercise_title: Optional[str] = None
    is_correct: bool


class CompletePracticeRequest(BaseModel):
    """Request to complete practice phase"""
    exercises_completed: int = Field(..., ge=0)
    exercises_correct: int = Field(..., ge=0)
    completed_exercises: Optional[List[CompletedExercise]] = None  # 具体完成的练习题列表


class CompletePracticeResponse(BaseModel):
    """Response after completing practice"""
    progress: UserStageProgressResponse
    can_start_verification: bool
    message: str


class StartVerificationRequest(BaseModel):
    """Request to start verification phase"""
    pass


class VerificationQuestion(BaseModel):
    """A verification question generated by AI"""
    id: str
    type: str  # choice, programming, fill_blank
    difficulty: int
    content: dict
    hints: Optional[List[str]] = None


class StartVerificationResponse(BaseModel):
    """Response with verification questions"""
    questions: List[VerificationQuestion]
    time_limit: int = 600  # seconds
    message: str = "Verification started"


class SubmitVerificationRequest(BaseModel):
    """Request to submit verification answers"""
    answers: dict[str, str | int]  # question_id -> answer


class SubmitVerificationResponse(BaseModel):
    """Response after submitting verification"""
    passed: bool
    correct_count: int
    total_count: int
    xp_earned: int
    quota_bonus: int
    progress: UserStageProgressResponse
    message: str


class StageListResponse(BaseModel):
    """Response for stage list endpoint"""
    stages: List[StageWithProgress]
    total: int


class StageDetailResponse(BaseModel):
    """Response for stage detail endpoint"""
    stage: StageDetail
    progress: Optional[UserStageProgressResponse] = None


# Stage Exercise Schemas
class StageExerciseSummary(BaseModel):
    """Summary of an exercise for stage practice"""
    id: int
    type: str
    difficulty: int
    content: dict
    hints: Optional[List[str]] = None
    knowledge_points: List[str] = Field(default_factory=list)
    test_cases: Optional[List[dict]] = None  # For programming exercises
    solution: Optional[dict] = None  # For choice questions

    model_config = {"from_attributes": True}


class StageExerciseListResponse(BaseModel):
    """Response for stage exercises list"""
    exercises: List[StageExerciseSummary]
    total: int


class GenerateExercisesRequest(BaseModel):
    """Request to generate exercises for a stage"""
    count: int = Field(default=5, ge=1, le=20)
    exercise_type: str = Field(default="choice", pattern="^(choice|programming|fill_blank)$")
    difficulty: int = Field(default=1, ge=1, le=5)
    topic: Optional[str] = None


class GenerateExercisesResponse(BaseModel):
    """Response after generating exercises"""
    success: bool
    generated: int
    exercises: List[dict]
    message: str


# Knowledge Check Schemas (知识点验证)
class KnowledgeCheckQuestion(BaseModel):
    """知识点验证选择题"""
    id: str
    question: str
    options: List[str]
    correct_answer: str
    explanation: Optional[str] = None
    knowledge_point: Optional[str] = None


class KnowledgeCheckRequest(BaseModel):
    """Request for knowledge check questions"""
    exercise_id: Optional[int] = None  # 刚完成的练习题ID
    count: int = Field(default=3, ge=2, le=5)  # 问题数量


class KnowledgeCheckResponse(BaseModel):
    """Response with knowledge check questions"""
    questions: List[KnowledgeCheckQuestion]
    stage_id: int
    message: str = "请回答以下问题验证你的理解"


class KnowledgeCheckSubmitRequest(BaseModel):
    """Request to submit knowledge check answers"""
    answers: dict[str, str]  # question_id -> answer


class KnowledgeCheckSubmitResponse(BaseModel):
    """Response after submitting knowledge check"""
    passed: bool
    correct_count: int
    total_count: int
    xp_earned: int = 0
    message: str
